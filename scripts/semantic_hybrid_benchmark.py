"""Benchmark Prometheist semantic retrieval policy before production integration.

This experiment measures the decisions still open for v0.6:
- semantic candidate window size (top 5/10/20/50 by default);
- generic versus per-query Qwen3 embedding instructions;
- semantic-only ranking versus deterministic lexical+semantic reciprocal-rank fusion;
- behavior on known-answer and explicit no-evidence questions.

The per-query instruction is generated by the normal stateless Qwen3 Instruct
model through Ollama with JSON-Schema-constrained output. Generation and
embedding models are never resident together. Instructions are cached under
benchmark_results so reruns do not repeatedly pay generation cost.

This script intentionally does not choose an evidence-admission threshold.
Previous measurements showed that raw cosine similarity overlaps between known
and unknown questions. The purpose here is to measure candidate recall/ranking
and route agreement so production policy can be selected from evidence.

Example:
    uv run python scripts/semantic_hybrid_benchmark.py \
        --instruction-model qwen3:4b-instruct \
        --embedding-model qwen3-embedding:4b-q4_K_M \
        --dimensions 1536 \
        --candidate-windows 5 10 20 50
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path
import re
import statistics
import time
from typing import Any, Iterable

import httpx
from pydantic import BaseModel, Field, ValidationError

import semantic_embedding_benchmark as base
from jit_agent.memory_kernel import tokenize

ROOT = Path(__file__).resolve().parent.parent
RESULTS_DIR = ROOT / "benchmark_results"
DEFAULT_INSTRUCTION_MODEL = "qwen3:4b-instruct"
DEFAULT_EMBEDDING_MODEL = "qwen3-embedding:4b-q4_K_M"
DEFAULT_DIMENSIONS = 1536
DEFAULT_WINDOWS = (5, 10, 20, 50)
RRF_K = 60
GENERIC_INSTRUCTION = (
    "Retrieve persisted internal-memory events that contain evidence needed "
    "to satisfy the current request."
)


class InstructionResult(BaseModel):
    instruction: str = Field(min_length=8, max_length=320)


INSTRUCTION_SCHEMA = InstructionResult.model_json_schema()

INSTRUCTION_SYSTEM = """\
You generate one embedding-retrieval instruction for one Prometheist internal-memory query.
Return only the required JSON object.
The instruction must be one concise sentence describing what persisted evidence would satisfy
this exact query. Do not answer the query, guess facts, name a likely answer, or invent entities.
Do not explain retrieval mechanics. Prefer the requested attribute, relationship, state, time,
comparison, constraint, or object when the query makes it explicit.
"""


def _safe_name(value: str) -> str:
    return re.sub(r"[^A-Za-z0-9_.-]+", "_", value).strip("_") or "model"


def _mean(values: Iterable[float]) -> float | None:
    values = list(values)
    return statistics.fmean(values) if values else None


def _median(values: Iterable[float]) -> float | None:
    values = list(values)
    return statistics.median(values) if values else None


def _post(client: httpx.Client, path: str, payload: dict[str, Any]) -> dict[str, Any]:
    response = client.post(path, json=payload)
    response.raise_for_status()
    return response.json()


def _generate_instruction(client: httpx.Client, model: str, query: str) -> tuple[str, float]:
    started = time.perf_counter()
    body = _post(
        client,
        "/api/chat",
        {
            "model": model,
            "messages": [
                {"role": "system", "content": INSTRUCTION_SYSTEM},
                {"role": "user", "content": query},
            ],
            "format": INSTRUCTION_SCHEMA,
            "think": False,
            "stream": False,
            "keep_alive": "10m",
            "options": {"temperature": 0, "num_predict": 96},
        },
    )
    wall = time.perf_counter() - started
    content = str((body.get("message") or {}).get("content") or "")
    try:
        parsed = InstructionResult.model_validate_json(content)
    except ValidationError as exc:
        raise RuntimeError(f"Instruction response failed schema validation: {content!r}") from exc
    instruction = " ".join(parsed.instruction.split())
    if "\n" in parsed.instruction or instruction.count(".") > 2:
        raise RuntimeError(f"Instruction was not concise enough: {instruction!r}")
    return instruction, wall


def _instruction_cache_path(model: str) -> Path:
    return RESULTS_DIR / f"semantic_query_instructions_{_safe_name(model)}.json"


def _load_cached_instructions(model: str, question_ids: list[str]) -> dict[str, str] | None:
    path = _instruction_cache_path(model)
    if not path.exists():
        return None
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None
    if payload.get("model") != model:
        return None
    instructions = payload.get("instructions") or {}
    if not all(question_id in instructions for question_id in question_ids):
        return None
    return {question_id: str(instructions[question_id]) for question_id in question_ids}


def _build_instructions(
    client: httpx.Client,
    model: str,
    questions: list[dict[str, Any]],
    *,
    force_regenerate: bool,
) -> tuple[dict[str, str], dict[str, Any]]:
    question_ids = [str(q["id"]) for q in questions]
    if not force_regenerate:
        cached = _load_cached_instructions(model, question_ids)
        if cached is not None:
            print(f"Instruction phase: reused {_instruction_cache_path(model).name}")
            return cached, {"cached": True, "wall_seconds": 0.0, "mean_query_ms": 0.0}

    installed = base._installed_model_names(client)
    if model not in installed:
        base._pull_model(client, model)

    print(f"Instruction phase: generating {len(questions)} per-query instructions with {model}")
    base._unload_everything(client)
    instructions: dict[str, str] = {}
    latencies: list[float] = []
    started = time.perf_counter()
    for index, question in enumerate(questions, start=1):
        instruction, wall = _generate_instruction(client, model, str(question["query"]))
        instructions[str(question["id"])] = instruction
        latencies.append(wall)
        print(f"  [{index:02d}/{len(questions):02d}] {question['id']}: {instruction}")
    total = time.perf_counter() - started
    base._unload_model(client, model)
    base._wait_unloaded(client, model)

    RESULTS_DIR.mkdir(exist_ok=True)
    cache_path = _instruction_cache_path(model)
    cache_path.write_text(
        json.dumps(
            {
                "model": model,
                "created_at": datetime.now(timezone.utc).isoformat(),
                "instructions": instructions,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    return instructions, {
        "cached": False,
        "wall_seconds": total,
        "mean_query_ms": 1000 * statistics.fmean(latencies),
        "median_query_ms": 1000 * statistics.median(latencies),
    }


def _dot(left: list[float], right: list[float]) -> float:
    return sum(a * b for a, b in zip(left, right, strict=True))


def _semantic_ranking(
    documents: list[dict[str, Any]],
    doc_vectors: list[list[float]],
    query_vector: list[float],
) -> list[dict[str, Any]]:
    rows = [
        {
            "event_id": str(document["id"]),
            "similarity": _dot(query_vector, doc_vector),
            "text": str(document["text"]),
        }
        for document, doc_vector in zip(documents, doc_vectors, strict=True)
    ]
    rows.sort(key=lambda row: (-float(row["similarity"]), str(row["event_id"])))
    return rows


def _lexical_ranking(documents: list[dict[str, Any]], query: str) -> list[dict[str, Any]]:
    query_terms = set(tokenize(query))
    rows: list[dict[str, Any]] = []
    for document in documents:
        doc_terms = set(tokenize(str(document["text"])))
        overlap = len(query_terms & doc_terms)
        coverage = overlap / len(query_terms) if query_terms else 0.0
        if overlap:
            rows.append(
                {
                    "event_id": str(document["id"]),
                    "overlap_terms": overlap,
                    "coverage": coverage,
                    "text": str(document["text"]),
                }
            )
    rows.sort(
        key=lambda row: (
            -int(row["overlap_terms"]),
            -float(row["coverage"]),
            str(row["event_id"]),
        )
    )
    return rows


def _rrf(
    semantic: list[dict[str, Any]],
    lexical: list[dict[str, Any]],
    window: int,
) -> list[dict[str, Any]]:
    scores: dict[str, float] = {}
    routes: dict[str, list[str]] = {}
    texts: dict[str, str] = {}
    for route, rows in (("semantic", semantic[:window]), ("lexical", lexical[:window])):
        for rank, row in enumerate(rows, start=1):
            event_id = str(row["event_id"])
            scores[event_id] = scores.get(event_id, 0.0) + 1.0 / (RRF_K + rank)
            routes.setdefault(event_id, []).append(route)
            texts[event_id] = str(row["text"])
    fused = [
        {
            "event_id": event_id,
            "rrf_score": score,
            "routes": sorted(routes[event_id]),
            "text": texts[event_id],
        }
        for event_id, score in scores.items()
    ]
    fused.sort(key=lambda row: (-float(row["rrf_score"]), str(row["event_id"])))
    return fused


def _rank_of(rows: list[dict[str, Any]], required: set[str]) -> int | None:
    return next(
        (rank for rank, row in enumerate(rows, start=1) if str(row["event_id"]) in required),
        None,
    )


def _evaluate_mode(
    *,
    mode: str,
    documents: list[dict[str, Any]],
    questions: list[dict[str, Any]],
    doc_vectors: list[list[float]],
    query_vectors: list[list[float]],
    windows: tuple[int, ...],
) -> dict[str, Any]:
    per_question: list[dict[str, Any]] = []
    for question, query_vector in zip(questions, query_vectors, strict=True):
        semantic = _semantic_ranking(documents, doc_vectors, query_vector)
        lexical = _lexical_ranking(documents, str(question["query"]))
        required = set(question.get("required_event_ids") or question.get("relevant_event_ids") or [])
        expect_none = bool(question.get("expect_no_evidence"))
        row: dict[str, Any] = {
            "question_id": question["id"],
            "query": question["query"],
            "expect_no_evidence": expect_none,
            "semantic_required_rank": _rank_of(semantic, required),
            "semantic_top_event_id": semantic[0]["event_id"],
            "semantic_top_similarity": semantic[0]["similarity"],
            "semantic_top_has_lexical_overlap": any(
                item["event_id"] == semantic[0]["event_id"] for item in lexical
            ),
            "windows": {},
        }
        for window in windows:
            fused = _rrf(semantic, lexical, window)
            row["windows"][str(window)] = {
                "semantic_candidate_hit": (
                    None if expect_none else _rank_of(semantic[:window], required) is not None
                ),
                "fused_required_rank": None if expect_none else _rank_of(fused, required),
                "fused_top_event_id": fused[0]["event_id"] if fused else None,
                "fused_top_routes": fused[0]["routes"] if fused else [],
                "semantic_top_in_lexical_window": any(
                    item["event_id"] == semantic[0]["event_id"] for item in lexical[:window]
                ),
            }
        per_question.append(row)

    known = [row for row in per_question if not row["expect_no_evidence"]]
    unknown = [row for row in per_question if row["expect_no_evidence"]]
    summary: dict[str, Any] = {
        "mode": mode,
        "known_questions": len(known),
        "unknown_questions": len(unknown),
        "semantic_mrr_full": _mean(
            1.0 / int(row["semantic_required_rank"])
            for row in known
            if row["semantic_required_rank"] is not None
        ),
        "semantic_recall_at_1": _mean(
            1.0 if row["semantic_required_rank"] == 1 else 0.0 for row in known
        ),
        "unknown_top1_similarity_max": max(
            (float(row["semantic_top_similarity"]) for row in unknown), default=None
        ),
        "unknown_top1_lexical_overlap_rate": _mean(
            1.0 if row["semantic_top_has_lexical_overlap"] else 0.0 for row in unknown
        ),
        "windows": {},
    }
    for window in windows:
        window_key = str(window)
        fused_ranks = [
            int(row["windows"][window_key]["fused_required_rank"])
            for row in known
            if row["windows"][window_key]["fused_required_rank"] is not None
        ]
        summary["windows"][window_key] = {
            "semantic_candidate_recall": _mean(
                1.0 if row["windows"][window_key]["semantic_candidate_hit"] else 0.0
                for row in known
            ),
            "fused_recall_at_1": _mean(
                1.0 if row["windows"][window_key]["fused_required_rank"] == 1 else 0.0
                for row in known
            ),
            "fused_recall_at_5": _mean(
                1.0
                if row["windows"][window_key]["fused_required_rank"] is not None
                and row["windows"][window_key]["fused_required_rank"] <= 5
                else 0.0
                for row in known
            ),
            "fused_mrr": _mean(1.0 / rank for rank in fused_ranks),
            "unknown_semantic_top_in_lexical_window_rate": _mean(
                1.0
                if row["windows"][window_key]["semantic_top_in_lexical_window"]
                else 0.0
                for row in unknown
            ),
            "unknown_fused_top_multiroute_rate": _mean(
                1.0
                if len(row["windows"][window_key]["fused_top_routes"]) > 1
                else 0.0
                for row in unknown
            ),
        }
    return {"summary": summary, "questions": per_question}


def _print_summary(result: dict[str, Any]) -> None:
    summary = result["summary"]
    print(f"\n{summary['mode'].upper()}")
    print(
        f"  full semantic: R@1={summary['semantic_recall_at_1']:.4f} "
        f"MRR={summary['semantic_mrr_full']:.4f} "
        f"unknown-max={summary['unknown_top1_similarity_max']:.6f}"
    )
    for window, row in summary["windows"].items():
        print(
            f"  top-{window:>2}: candidate-recall={row['semantic_candidate_recall']:.4f} "
            f"fused-R@1={row['fused_recall_at_1']:.4f} "
            f"fused-R@5={row['fused_recall_at_5']:.4f} "
            f"fused-MRR={row['fused_mrr']:.4f} "
            f"unknown-multiroute={row['unknown_fused_top_multiroute_rate']:.4f}"
        )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--instruction-model", default=DEFAULT_INSTRUCTION_MODEL)
    parser.add_argument("--embedding-model", default=DEFAULT_EMBEDDING_MODEL)
    parser.add_argument("--dimensions", type=int, default=DEFAULT_DIMENSIONS)
    parser.add_argument(
        "--candidate-windows",
        type=int,
        nargs="+",
        default=list(DEFAULT_WINDOWS),
    )
    parser.add_argument("--ollama-url", default="http://127.0.0.1:11434")
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--force-regenerate-instructions", action="store_true")
    args = parser.parse_args()

    windows = tuple(sorted(set(args.candidate_windows)))
    if any(value < 1 for value in windows):
        raise SystemExit("candidate windows must all be >= 1")

    documents, questions = base._load_corpora(list(base.DEFAULT_CORPORA))
    print(f"Loaded {len(documents)} events and {len(questions)} questions.")
    print(f"Candidate windows: {', '.join(str(value) for value in windows)}")
    print("Exclusive model mode is ON.\n")

    RESULTS_DIR.mkdir(exist_ok=True)
    with httpx.Client(base_url=args.ollama_url, timeout=300.0) as client:
        base._unload_everything(client)
        instructions, instruction_metrics = _build_instructions(
            client,
            args.instruction_model,
            questions,
            force_regenerate=args.force_regenerate_instructions,
        )

        if base._running_models(client):
            base._unload_everything(client)
        installed = base._installed_model_names(client)
        if args.embedding_model not in installed:
            base._pull_model(client, args.embedding_model)

        print(f"\nEmbedding documents with {args.embedding_model} at {args.dimensions} dimensions...")
        doc_vectors, doc_metrics = base._embed_many(
            client,
            model=args.embedding_model,
            texts=[str(document["text"]) for document in documents],
            dimensions=args.dimensions,
            batch_size=args.batch_size,
            keep_alive="10m",
        )

        modes: dict[str, list[str]] = {
            "generic_instruction": [
                base._format_query(str(q["query"]), GENERIC_INSTRUCTION, True)
                for q in questions
            ],
            "per_query_instruction": [
                base._format_query(
                    str(q["query"]),
                    instructions[str(q["id"])],
                    True,
                )
                for q in questions
            ],
        }

        results: dict[str, Any] = {}
        query_metrics: dict[str, Any] = {}
        for mode, query_texts in modes.items():
            print(f"Embedding {len(query_texts)} queries: {mode}...")
            query_vectors, metrics = base._embed_many(
                client,
                model=args.embedding_model,
                texts=query_texts,
                dimensions=args.dimensions,
                batch_size=args.batch_size,
                keep_alive="10m",
            )
            query_metrics[mode] = metrics
            result = _evaluate_mode(
                mode=mode,
                documents=documents,
                questions=questions,
                doc_vectors=doc_vectors,
                query_vectors=query_vectors,
                windows=windows,
            )
            results[mode] = result
            _print_summary(result)

        base._unload_model(client, args.embedding_model)
        base._wait_unloaded(client, args.embedding_model)

    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    output = RESULTS_DIR / f"semantic_hybrid_{stamp}.json"
    payload = {
        "benchmark": "prometheist-semantic-hybrid-v1",
        "created_at": datetime.now(timezone.utc).isoformat(),
        "instruction_model": args.instruction_model,
        "embedding_model": args.embedding_model,
        "embedding_dimensions": args.dimensions,
        "candidate_windows": list(windows),
        "rrf_k": RRF_K,
        "generic_instruction": GENERIC_INSTRUCTION,
        "instructions": instructions,
        "instruction_metrics": instruction_metrics,
        "document_embedding_metrics": doc_metrics,
        "query_embedding_metrics": query_metrics,
        "results": results,
    }
    output.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    print(f"\nWrote {output}")


if __name__ == "__main__":
    main()
